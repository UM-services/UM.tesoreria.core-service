-- Migración de la emisión individual de chequeras (frmImpChequera de tesoreria.vb6)
-- Borrador persistido: permite editar la chequera antes de emitirla y repetir
-- la entrega (PDF / correo) sin volver a emitir.
-- Fechas: DATETIME(6) según convención del proyecto.

CREATE TABLE IF NOT EXISTS chequera_borrador (
    chb_id BIGINT NOT NULL AUTO_INCREMENT,
    chb_estado VARCHAR(16) NOT NULL DEFAULT 'ABIERTO',
    chb_persona_id DECIMAL(19, 0) NOT NULL,
    chb_documento_id INT NOT NULL,
    chb_facultad_id INT NOT NULL,
    chb_lectivo_id INT NOT NULL,
    chb_tipo_chequera_id INT NOT NULL,
    chb_arancel_tipo_id INT NOT NULL DEFAULT 0,
    chb_alternativa_id INT NULL,
    chb_curso_id INT NULL,
    chb_chequera_serie_id BIGINT NULL,
    chb_fecha DATETIME(6) NULL,
    chb_hpum TINYINT NOT NULL DEFAULT 0,
    chb_beca_porcentaje DECIMAL(9, 4) NOT NULL DEFAULT 0.0000,
    chb_beca_resolucion VARCHAR(255) NULL,
    chb_beca_fecha DATETIME(6) NULL,
    chb_beca_user_id BIGINT NULL,
    chb_calcula_beca TINYINT NOT NULL DEFAULT 0,
    chb_email_personal VARCHAR(255) NULL,
    chb_email_institucional VARCHAR(255) NULL,
    chb_email_copia VARCHAR(255) NULL,
    chb_incluye_barras TINYINT NOT NULL DEFAULT 1,
    chb_copia_facultad TINYINT NOT NULL DEFAULT 0,
    chb_chequera_id BIGINT NULL,
    chb_chequera_serie_id_emitida BIGINT NULL,
    chb_auditoria_id VARCHAR(36) NULL,
    chb_clave_idempotencia VARCHAR(64) NULL,
    chb_usuario_id VARCHAR(64) NULL,
    chb_version INT NOT NULL DEFAULT 0,
    created DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated DATETIME(6) NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP(6),
    emitido_at DATETIME(6) NULL,
    PRIMARY KEY (chb_id),
    UNIQUE KEY uk_chequera_borrador_idempotencia (chb_clave_idempotencia),
    KEY ix_chequera_borrador_usuario_estado (chb_usuario_id, chb_estado),
    KEY ix_chequera_borrador_persona (chb_persona_id, chb_documento_id, chb_lectivo_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS chequera_borrador_cuota (
    chbc_id BIGINT NOT NULL AUTO_INCREMENT,
    chbc_borrador_id BIGINT NOT NULL,
    chbc_chequera_cuota_id BIGINT NULL,
    chbc_producto_id INT NOT NULL,
    chbc_alternativa_id INT NOT NULL,
    chbc_cuota_id INT NOT NULL,
    chbc_mes INT NULL,
    chbc_anio INT NULL,
    chbc_1er_vencimiento DATETIME(6) NULL,
    chbc_2do_vencimiento DATETIME(6) NULL,
    chbc_3er_vencimiento DATETIME(6) NULL,
    chbc_1er_importe_original DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
    chbc_2do_importe_original DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
    chbc_3er_importe_original DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
    chbc_1er_importe_borrador DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
    chbc_2do_importe_borrador DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
    chbc_3er_importe_borrador DECIMAL(14, 2) NOT NULL DEFAULT 0.00,
    chbc_arancel_tipo_id INT NULL,
    chbc_tramo_id INT NULL,
    chbc_descuento_pt DECIMAL(9, 4) NOT NULL DEFAULT 0.0000,
    chbc_pagado TINYINT NOT NULL DEFAULT 0,
    chbc_baja TINYINT NOT NULL DEFAULT 0,
    chbc_manual TINYINT NOT NULL DEFAULT 0,
    chbc_compensada TINYINT NOT NULL DEFAULT 0,
    chbc_modificado TINYINT NOT NULL DEFAULT 0,
    chbc_bloqueado TINYINT NOT NULL DEFAULT 0,
    created DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated DATETIME(6) NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (chbc_id),
    UNIQUE KEY uk_chequera_borrador_cuota (chbc_borrador_id, chbc_producto_id, chbc_alternativa_id, chbc_cuota_id),
    CONSTRAINT fk_chequera_borrador_cuota_borrador
        FOREIGN KEY (chbc_borrador_id) REFERENCES chequera_borrador (chb_id) ON DELETE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;
